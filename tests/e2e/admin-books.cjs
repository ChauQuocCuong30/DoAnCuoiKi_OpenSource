// Requires tests/integration/admin-books.php on a disposable *_test database.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.TEST_BASE_URL;
if (!base) throw new Error('Set TEST_BASE_URL to the isolated test server.');
(async () => {
    const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE, args: ['--no-sandbox'] });
    try {
        const guest = await browser.newContext();
        for (const path of ['/api/v1/admin/content/books', '/api/v1/admin/content/samples', '/api/v1/admin/content/csv/template']) {
            assert.equal((await guest.request.get(base + path)).status(), 401, path);
        }
        assert.equal((await guest.request.post(base + '/api/v1/admin/content/csv/import', { data: {} })).status(), 401);
        const reader = await browser.newContext();
        assert.equal((await reader.request.post(base + '/api/v1/auth/login', { data: { email: 'books-user@example.test', password: 'books-test-password-123' } })).status(), 200);
        assert.equal((await reader.request.get(base + '/admin/words')).status(), 403);
        assert.equal((await reader.request.post(base + '/api/v1/admin/content/samples/preview', { data: {} })).status(), 403);
        assert.equal((await reader.request.post(base + '/api/v1/admin/content/csv/import', { data: {} })).status(), 403);
        const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
        assert.equal((await context.request.post(base + '/api/v1/auth/login', { data: { email: 'books-admin@example.test', password: 'books-test-password-123' } })).status(), 200);
        const api = '/api/v1/admin/content';
        const get = async (path) => { const r = await context.request.get(base + api + path); assert.equal(r.status(), 200, await r.text()); return (await r.json()).data; };
        const boot = await get('/bootstrap'), headers = { 'X-CSRF-Token': boot.csrf_token };
        const books = (await get('/books')).items, book = books.find((b) => b.name === 'Admin book test');
        assert(book); const bookId = String(book.id);
        assert.equal((await get('/samples')).items.length, 10);
        assert.equal((await context.request.post(base + api + '/samples/preview', { data: { sample_key: 'drinks', topic_id: bookId, duplicate_mode: 'skip' } })).status(), 403);
        const post = (path, data) => context.request.post(base + api + path, { headers, data });
        assert.equal((await context.request.post(base + api + '/csv/import', { data: {} })).status(), 403, 'Direct import requires CSRF');
        const a = await post('/samples/preview', { sample_key: 'food', topic_id: bookId, duplicate_mode: 'skip' });
        const oldToken = (await a.json()).data.preview_token;
        await post('/samples/preview', { sample_key: 'animals', topic_id: bookId, duplicate_mode: 'skip' });
        assert.equal((await post('/csv/commit', { preview_token: oldToken })).status(), 422, 'Replaced preview token is rejected');
        assert.equal((await post('/samples/preview', { sample_key: '../bad', topic_id: bookId, duplicate_mode: 'skip' })).status(), 404);
        const template = await context.request.get(base + api + '/csv/template');
        assert.equal(template.status(), 200); assert.match(template.headers()['content-type'], /text\/csv/);
        assert.match(await template.text(), /english,vietnamese,part_of_speech,example/);
        const page = await context.newPage();
        const errors = []; page.on('pageerror', (e) => errors.push(e.message));
        await page.goto(base + '/admin/words');
        await page.getByRole('button', { name: 'Mở sách Admin book test, 0 từ' }).waitFor();
        assert.equal(await page.locator('.book-cover img').count(), 0);
        assert.equal(await page.evaluate(() => window.adminXss), undefined, 'Topic labels are text, not HTML');
        if (process.env.ADMIN_SCREENSHOT_DIR) {
            fs.mkdirSync(process.env.ADMIN_SCREENSHOT_DIR, { recursive: true });
            await page.screenshot({ path: process.env.ADMIN_SCREENSHOT_DIR + '/shelf-before.png', fullPage: true });
        }
        await page.getByRole('button', { name: 'Mở sách Admin book test, 0 từ' }).click();
        await page.locator('#book-import').click();
        assert.equal(await page.locator('#import-topic').inputValue(), bookId);
        assert.equal(await page.locator('#sample-key option').count(), 10);
        const previewResponse = page.waitForResponse((r) => r.url().endsWith('/samples/preview'));
        await page.locator('#preview-import').click();
        const preview = (await (await previewResponse).json()).data;
        assert.equal(preview.valid_count, 20); assert.equal(preview.skipped_count, 0);
        await page.locator('#commit-import:enabled').waitFor();
        await page.locator('#commit-import').click();
        await page.getByText('Đã nhập 20 từ vào Admin book test. Bỏ qua 0 từ trùng.', { exact: true }).last().waitFor();
        assert.equal((await get('/words?parent_id=' + bookId)).total, 20);
        const replay = await post('/csv/commit', { preview_token: preview.preview_token });
        assert.equal(replay.status(), 200); assert.equal((await replay.json()).data.imported, 20);
        assert.equal((await get('/words?parent_id=' + bookId)).total, 20, 'Retry never creates duplicate words');
        await page.getByRole('button', { name: 'Đóng', exact: true }).click();
        await page.locator('#word-search').fill('milk'); await page.locator('#word-filter button').click();
        await page.getByRole('button', { name: 'Ẩn từ milk', exact: true }).click();
        await page.getByRole('button', { name: 'Hiện từ milk', exact: true }).waitFor();
        const milk = (await get('/words?parent_id=' + bookId + '&q=milk')).items[0];
        assert.equal(Number(milk.is_active), 0);
        await page.locator('#book-import').click();
        await page.locator('#preview-import').click();
        await page.getByText('Các từ này đã có trong sách. Không cần nhập lại.', { exact: true }).waitFor();
        assert.equal(await page.locator('#commit-import').isDisabled(), true);
        assert.equal(Number((await get('/words/' + milk.id)).is_active), 0, 'Reimport leaves hidden data alone');
        // CSV errors, then a complete valid multipart import with duplicate and hostile text.
        await page.getByRole('radio', { name: 'File CSV của bạn', exact: true }).check();
        const csvHeader = 'english,vietnamese,part_of_speech,example,example_translation\n';
        const file = (text) => ({ name: 'words.csv', mimeType: 'text/csv', buffer: Buffer.from(text, 'utf8') });
        await page.locator('#csv-file').setInputFiles(file(csvHeader + 'bad,,noun,A word.,Một từ.\n'));
        const badImportResponse = page.waitForResponse((r) => r.request().method() === 'POST' && r.url().endsWith('/csv/import'));
        await page.locator('#preview-import').click();
        const badImport = await badImportResponse;
        assert.equal(badImport.status(), 422);
        assert.equal((await badImport.json()).error.code, 'CSV_INVALID');
        await page.locator('#import-message.is-error').waitFor();
        assert.equal((await get('/words?parent_id=' + bookId)).total, 20, 'Invalid CSV writes nothing');
        assert.equal(await page.locator('#commit-import').isDisabled(), true);
        const csv = csvHeader + 'pear,quả lê,noun,A pear.,Một quả lê.\npeach,quả đào,noun,A peach.,Một quả đào.\n' +
            'injection,"<img src=x onerror=""window.adminXss=1"">",noun,Plain text.,Văn bản thường.\nmilk,sữa,noun,I drink milk.,Tôi uống sữa.\n';
        await page.locator('#csv-file').setInputFiles(file(csv));
        const importResponse = page.waitForResponse((r) => r.request().method() === 'POST' && r.url().endsWith('/csv/import'));
        await page.locator('#preview-import').click();
        const imported = await importResponse;
        assert.equal(imported.status(), 201, await imported.text());
        const importedData = (await imported.json()).data;
        assert.equal(importedData.imported, 3);
        assert.equal(importedData.skipped, 1);
        assert.equal(importedData.updated, 0);
        await page.getByText('Đã lưu vào CSDL: 3 từ mới, 0 từ cập nhật, 1 từ bỏ qua.', { exact: true }).last().waitFor();
        assert.equal((await get('/words?parent_id=' + bookId)).total, 23, 'CSV persists without a second confirmation');
        assert.equal(Number((await get('/words/' + milk.id)).is_active), 0, 'Direct import does not restore hidden duplicates');
        assert.equal(await page.locator('#commit-import').isDisabled(), true);
        assert.equal(await page.locator('#words img').count(), 0, 'Imported HTML stays text');
        assert.equal(await page.evaluate(() => window.adminXss), undefined);
        await page.getByRole('button', { name: 'Đóng', exact: true }).click();
        await page.locator('#word-search').fill(''); await page.locator('#word-filter button').click();
        await page.getByText('Trang 1 / 2', { exact: true }).waitFor();
        await page.locator('#next-page').click(); await page.getByText('Trang 2 / 2', { exact: true }).waitFor();
        assert.equal(await page.locator('#words tr').count(), 3, 'Pagination reaches the final persisted words');
        await page.locator('#word-search').fill('pear'); await page.locator('#word-filter button').click();
        await page.getByRole('button', { name: 'Sửa từ pear', exact: true }).click();
        await page.locator('#word-form [name=vietnamese]').fill('quả lê chín');
        await page.locator('#save-word').click(); await page.getByText('quả lê chín', { exact: true }).waitFor();
        assert.equal(await page.locator('#new-word').count(), 0);
        assert.equal((await get('/words?parent_id=' + bookId)).total, 23);
        await page.locator('#book-import').click();
        await page.locator('#sample-key').selectOption('animals'); await page.locator('#preview-import').click();
        await page.locator('#commit-import:enabled').waitFor();
        await page.locator('#sample-key').selectOption('food');
        assert.equal(await page.locator('#commit-import').isDisabled(), true, 'Changing inputs invalidates the old preview');
        await page.getByRole('button', { name: 'Đóng', exact: true }).click();
        await page.locator('#back-library').click();
        await page.getByRole('button', { name: 'Mở sách Hidden admin book, 0 từ' }).click();
        assert.equal(await page.locator('#new-word').count(), 0);
        assert.equal(await page.locator('#book-import').isDisabled(), true);
        await page.locator('#back-library').click();
        await page.locator('#book-search').fill('admin book test');
        assert.equal(await page.locator('.book-cover').count(), 1);
        await page.locator('#book-search').fill('');
        if (process.env.ADMIN_SCREENSHOT_DIR) await page.screenshot({ path: process.env.ADMIN_SCREENSHOT_DIR + '/shelf-after.png', fullPage: true });
        await page.setViewportSize({ width: 390, height: 844 });
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile shelf has no horizontal overflow');
        await page.getByRole('button', { name: 'Mở sách Admin book test, 23 từ' }).click();
        await page.locator('#word-search').fill('injection'); await page.locator('#word-filter button').click();
        await page.getByRole('button', { name: 'Sửa từ injection', exact: true }).waitFor();
        assert.equal(await page.locator('#words img').count(), 0); assert.equal(await page.evaluate(() => window.adminXss), undefined);
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile book keeps table scrolling inside its container');
        if (process.env.ADMIN_SCREENSHOT_DIR) await page.screenshot({ path: process.env.ADMIN_SCREENSHOT_DIR + '/book-mobile.png', fullPage: true });
        assert.equal(errors.length, 0, errors.join('\n'));
        assert.equal((await context.request.get(base + '/learning')).status(), 200);
        console.log('PASS: admin auth/CSRF, sample import/retry, hidden duplicates, multipart CSV, atomic errors, search/pagination, editing, legacy routes, lesson preservation, XSS and mobile layout');
    } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exit(1); });
